// Export utilities for analysis reports

import { AnalysisResult } from './types';

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}

export function generateSummaryText(analysis: AnalysisResult): string {
  const lines: string[] = [];
  lines.push(`Document Type: ${analysis.documentType}`);
  if (analysis.issuingOrganization) {
    lines.push(`Issuing Organization: ${analysis.issuingOrganization}`);
  }
  if (analysis.documentDate) {
    lines.push(`Document Date: ${analysis.documentDate}`);
  }
  lines.push('');
  lines.push('Summary:');
  analysis.summary.forEach((s) => lines.push(`  • ${s}`));
  return lines.join('\n');
}

export function generateChecklistText(analysis: AnalysisResult): string {
  const lines: string[] = ['Action Checklist:', ''];
  analysis.actionItems.forEach((item, i) => {
    const priority = `[${item.priority.toUpperCase()}]`;
    lines.push(`${i + 1}. ${priority} ${item.title}`);
    lines.push(`   ${item.description}`);
    if (item.deadline) {
      lines.push(`   Deadline: ${item.deadline}`);
    }
    lines.push('');
  });
  return lines.join('\n');
}

export function generateFullReport(analysis: AnalysisResult): string {
  const lines: string[] = [];

  lines.push('# Document Decoder — Analysis Report');
  lines.push('');
  lines.push(`**Document Type:** ${analysis.documentType}`);
  if (analysis.issuingOrganization) {
    lines.push(`**Issuing Organization:** ${analysis.issuingOrganization}`);
  }
  if (analysis.documentDate) {
    lines.push(`**Document Date:** ${analysis.documentDate}`);
  }
  lines.push('');

  // Summary
  lines.push('## Summary');
  lines.push('');
  analysis.summary.forEach((s) => lines.push(`- ${s}`));
  lines.push('');

  // Key Facts
  if (analysis.keyFacts.length > 0) {
    lines.push('## Key Facts');
    lines.push('');
    analysis.keyFacts.forEach((fact) => {
      lines.push(`- **${fact.label}:** ${fact.value}`);
      if (fact.sourceQuote) {
        lines.push(`  > "${fact.sourceQuote}"${fact.page ? ` (Page ${fact.page})` : ''}`);
      }
    });
    lines.push('');
  }

  // Deadlines
  if (analysis.deadlines.length > 0) {
    lines.push('## Deadlines');
    lines.push('');
    analysis.deadlines.forEach((d) => {
      lines.push(`- **${d.dateText}** — ${d.action}`);
      if (d.sourceQuote) {
        lines.push(`  > "${d.sourceQuote}"${d.page ? ` (Page ${d.page})` : ''}`);
      }
    });
    lines.push('');
  }

  // Action Items
  if (analysis.actionItems.length > 0) {
    lines.push('## Action Checklist');
    lines.push('');
    analysis.actionItems.forEach((item, i) => {
      const priority = `[${item.priority.toUpperCase()}]`;
      lines.push(`${i + 1}. ${priority} **${item.title}**`);
      lines.push(`   ${item.description}`);
      if (item.deadline) lines.push(`   *Deadline: ${item.deadline}*`);
      if (item.sourceQuote) {
        lines.push(`   > "${item.sourceQuote}"${item.page ? ` (Page ${item.page})` : ''}`);
      }
      lines.push('');
    });
  }

  // Missing Information
  if (analysis.missingInformation.length > 0) {
    lines.push('## Missing or Unclear Information');
    lines.push('');
    analysis.missingInformation.forEach((m) => {
      lines.push(`- **${m.item}:** ${m.reason}`);
    });
    lines.push('');
  }

  // Plain Language Explanations
  if (analysis.plainLanguageExplanations.length > 0) {
    lines.push('## Difficult Wording Explained');
    lines.push('');
    analysis.plainLanguageExplanations.forEach((p) => {
      lines.push(`**Original:** "${p.originalText}"`);
      lines.push('');
      lines.push(`**Plain English:** ${p.explanation}`);
      lines.push('');
    });
  }

  // Limitations
  if (analysis.limitations.length > 0) {
    lines.push('---');
    lines.push('');
    lines.push('*Limitations:*');
    analysis.limitations.forEach((l) => lines.push(`- ${l}`));
    lines.push('');
  }

  lines.push('---');
  lines.push('*Generated by Document Decoder — Powered by Sarvam AI*');

  return lines.join('\n');
}

export function downloadReport(analysis: AnalysisResult): void {
  const content = generateFullReport(analysis);
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `document-decoder-report-${Date.now()}.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
